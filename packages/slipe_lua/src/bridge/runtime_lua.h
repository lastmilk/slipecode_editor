#ifndef SLIPE_LUA_RUNTIME_LUA_H
#define SLIPE_LUA_RUNTIME_LUA_H

/* This source is deliberately embedded so every VM gets the same private
 * registration API without installing files or depending on a host Lua. */
static const char slipe_runtime_lua[] =
"local registry, handlers, yield_next, json_encode, json_decode, mark_array, json_null = ...\n"
"local next_id = 0\n"
"local current_schema = nil\n"
"local initialized_capabilities = {}\n"
"local function new_id(handler)\n"
"  next_id = next_id + 1\n"
"  local id = 'handler:' .. next_id\n"
"  handlers[id] = handler\n"
"  return id\n"
"end\n"
"local function check_string(value, name)\n"
"  if type(value) ~= 'string' or #value == 0 then\n"
"    error(name .. ' must be a non-empty string', 3)\n"
"  end\n"
"  return value\n"
"end\n"
"local function check_handler(value)\n"
"  if type(value) ~= 'function' then error('handler must be a function', 3) end\n"
"  return value\n"
"end\n"
"local function priority(options)\n"
"  local value = options.priority\n"
"  if value == nil then return 0 end\n"
"  if type(value) ~= 'number' or value ~= math.floor(value) then\n"
"    error('priority must be an integer', 3)\n"
"  end\n"
"  return value\n"
"end\n"
"local function add_list_entry(group, name, entry)\n"
"  local list = group[name]\n"
"  if list == nil then\n"
"    list = {}\n"
"    mark_array(list)\n"
"    group[name] = list\n"
"  end\n"
"  list[#list + 1] = entry\n"
"end\n"
"local slipe = { service = {}, events = {}, commands = {}, config = {}, keys = {}, json = {}, schema = {}, ui = {} }\n"
"local function checked(schema, value)\n"
"  if current_schema == nil or schema == nil then return end\n"
"  local ok, message = slipe.schema.validate(value, schema)\n"
"  if not ok then error(message, 3) end\n"
"end\n"
"function slipe.service.override(service, operation, options, handler)\n"
"  if not initialized_capabilities['editor.modify'] then error(\"pluginhook.init editor.modify is required before overriding editor services\", 2) end\n"
"  check_string(service, 'service')\n"
"  check_string(operation, 'operation')\n"
"  if type(options) == 'function' then handler, options = options, {} end\n"
"  options = options or {}\n"
"  if type(options) ~= 'table' then error('options must be a table', 2) end\n"
"  local user_handler = check_handler(handler)\n"
"  handler = function(request, next)\n"
"    local operation_schema = current_schema and current_schema.services[service] and current_schema.services[service].operations[operation]\n"
"    checked(operation_schema and operation_schema.request, request)\n"
"    local checked_next = function(next_request)\n"
"      checked(operation_schema and operation_schema.request, next_request)\n"
"      return next(next_request)\n"
"    end\n"
"    local result = user_handler(request, checked_next)\n"
"    checked(operation_schema and operation_schema.response, result)\n"
"    return result\n"
"  end\n"
"  local id = new_id(handler)\n"
"  local key = service .. '.' .. operation\n"
"  add_list_entry(registry.services, key, { id = id, service = service, operation = operation, priority = priority(options), handler = id })\n"
"  return id\n"
"end\n"
"function slipe.events.on(event_type, options, handler)\n"
"  check_string(event_type, 'event type')\n"
"  if type(options) == 'function' then handler, options = options, {} end\n"
"  options = options or {}\n"
"  if type(options) ~= 'table' then error('options must be a table', 2) end\n"
"  check_handler(handler)\n"
"  local phase = options.phase or 'will'\n"
"  if phase ~= 'will' and phase ~= 'did' then error('phase must be will or did', 2) end\n"
"  if phase == 'will' and not initialized_capabilities['editor.modify'] then error('pluginhook.init editor.modify is required for will events', 2) end\n"
"  local user_handler = check_handler(handler)\n"
"  handler = function(event)\n"
"    checked(current_schema and current_schema.event, event)\n"
"    local result = user_handler(event)\n"
"    if result ~= nil then checked(current_schema and current_schema.eventDecision, result) end\n"
"    if phase == 'did' and result ~= nil and result.action ~= 'continue' then error('did events are read-only', 2) end\n"
"    return result\n"
"  end\n"
"  local id = new_id(handler)\n"
"  add_list_entry(registry.events, event_type, { id = id, type = event_type, phase = phase, priority = priority(options), handler = id })\n"
"  return id\n"
"end\n"
"function slipe.events.off(id)\n"
"  check_string(id, 'handler id')\n"
"  for event_type, list in pairs(registry.events) do\n"
"    for index, entry in ipairs(list) do\n"
"      if entry.id == id then\n"
"        table.remove(list, index)\n"
"        handlers[id] = nil\n"
"        return true\n"
"      end\n"
"    end\n"
"  end\n"
"  return false\n"
"end\n"
"function slipe.commands.register(command, options, handler)\n"
"  check_string(command, 'command')\n"
"  if type(options) == 'function' then handler, options = options, {} end\n"
"  options = options or {}\n"
"  if type(options) ~= 'table' then error('options must be a table', 2) end\n"
"  check_handler(handler)\n"
"  local id = new_id(handler)\n"
"  local entry = { registration = id, id = command, handler = id }\n"
"  for key, value in pairs(options) do entry[key] = value end\n"
"  entry.id, entry.handler, entry.registration = command, id, id\n"
"  registry.commands[command] = entry\n"
"  return id\n"
"end\n"
"function slipe.commands.unregister(command)\n"
"  check_string(command, 'command')\n"
"  local entry = registry.commands[command]\n"
"  if entry == nil then return false end\n"
"  handlers[entry.handler] = nil\n"
"  registry.commands[command] = nil\n"
"  return true\n"
"end\n"
"function slipe.config.set(key, value)\n"
"  check_string(key, 'configuration key')\n"
"  local configuration = current_schema and current_schema.configuration\n"
"  if configuration and configuration.additionalProperties == false and configuration.properties[key] == nil then error('unknown configuration key: ' .. key, 2) end\n"
"  checked(configuration and configuration.properties[key], value)\n"
"  registry.config[key] = value\n"
"  return value\n"
"end\n"
"function slipe.keys.bind(activator, command)\n"
"  check_string(activator, 'activator')\n"
"  check_string(command, 'command')\n"
"  registry.keys[activator] = command\n"
"  return true\n"
"end\n"
"function slipe.keys.unbind(activator)\n"
"  check_string(activator, 'activator')\n"
"  registry.keys[activator] = false\n"
"  return true\n"
"end\n"
"slipe.json.encode = json_encode\n"
"slipe.json.decode = json_decode\n"
"slipe.json.null = json_null\n"
"local function type_matches(expected, value)\n"
"  local actual = type(value)\n"
"  if expected == 'any' then return true end\n"
"  if expected == 'null' then return value == json_null end\n"
"  if expected == 'object' or expected == 'array' then return actual == 'table' end\n"
"  if expected == 'integer' then return actual == 'number' and value == math.floor(value) end\n"
"  if expected == 'number' then return actual == 'number' and value == value and value ~= math.huge and value ~= -math.huge end\n"
"  return actual == expected\n"
"end\n"
"local function validate(schema, value, path)\n"
"  if type(schema) ~= 'table' then return nil, path .. ': schema must be a table' end\n"
"  local expected = schema.type\n"
"  if expected ~= nil and not type_matches(expected, value) then\n"
"    return nil, path .. ': expected ' .. expected .. ', got ' .. type(value)\n"
"  end\n"
"  if schema.enum ~= nil then\n"
"    local found = false\n"
"    for _, candidate in ipairs(schema.enum) do if value == candidate then found = true break end end\n"
"    if not found then return nil, path .. ': value is not in enum' end\n"
"  end\n"
"  if type(value) == 'string' then\n"
"    if schema.minLength and #value < schema.minLength then return nil, path .. ': string is too short' end\n"
"    if schema.maxLength and #value > schema.maxLength then return nil, path .. ': string is too long' end\n"
"  elseif type(value) == 'number' then\n"
"    if schema.minimum and value < schema.minimum then return nil, path .. ': number is below minimum' end\n"
"    if schema.maximum and value > schema.maximum then return nil, path .. ': number is above maximum' end\n"
"  elseif type(value) == 'table' and expected == 'object' then\n"
"    local properties = schema.properties or {}\n"
"    for _, key in ipairs(schema.required or {}) do\n"
"      if value[key] == nil then return nil, path .. '.' .. key .. ': required field is missing' end\n"
"    end\n"
"    for key, item in pairs(value) do\n"
"      local child = properties[key]\n"
"      if child == nil then\n"
"        if schema.additionalProperties == false then return nil, path .. '.' .. tostring(key) .. ': unknown field' end\n"
"      else\n"
"        local ok, message = validate(child, item, path .. '.' .. key)\n"
"        if not ok then return nil, message end\n"
"      end\n"
"    end\n"
"  elseif type(value) == 'table' and expected == 'array' then\n"
"    local length = #value\n"
"    if schema.minItems and length < schema.minItems then return nil, path .. ': array is too short' end\n"
"    if schema.maxItems and length > schema.maxItems then return nil, path .. ': array is too long' end\n"
"    if schema.items then\n"
"      for index, item in ipairs(value) do\n"
"        local ok, message = validate(schema.items, item, path .. '[' .. index .. ']')\n"
"        if not ok then return nil, message end\n"
"      end\n"
"    end\n"
"  end\n"
"  return true\n"
"end\n"
"function slipe.schema.load(schema)\n"
"  if type(schema) ~= 'table' then error('schema must be a table', 2) end\n"
"  current_schema = schema\n"
"  return true\n"
"end\n"
"function slipe.schema.validate(value, schema)\n"
"  schema = schema or current_schema\n"
"  if schema == nil then return nil, 'schema: no schema loaded' end\n"
"  return validate(schema, value, '$')\n"
"end\n"
"function slipe.ui.notify(message, level)\n"
"  local request = { message = message, level = level }\n"
"  local operation = current_schema and current_schema.services.ui.operations.notify\n"
"  checked(operation and operation.request, request)\n"
"  local is_error, result = yield_next({ kind = 'service', service = 'ui', operation = 'notify', payload = request })\n"
"  if is_error then error(type(result) == 'table' and result.message or tostring(result), 0) end\n"
"  checked(operation and operation.response, result)\n"
"  return result\n"
"end\n"
"_G.slipe = slipe\n"
"_G.pluginhook = {}\n"
"function pluginhook.init(options)\n"
"  if type(options) ~= 'table' then error('options must be a table', 2) end\n"
"  local capability = check_string(options.capability, 'capability')\n"
"  local reason = check_string(options.reason, 'reason')\n"
"  registry.hooks[#registry.hooks + 1] = { capability = capability, reason = reason }\n"
"  initialized_capabilities[capability] = true\n"
"  return true\n"
"end\n"
"return function(initial_payload)\n"
"  return function(payload)\n"
"    if payload == nil then payload = initial_payload end\n"
"    local is_error, result = yield_next({ kind = 'next', payload = payload })\n"
"    if is_error then error(result, 0) end\n"
"    return result\n"
"  end\n"
"end\n";

#endif
