    var text = table[key] ?? _values['zh']![key] ?? key;
    if (vars != null) {
      for (final entry in vars.entries) {
        text = text.replaceAll('{${entry.key}}', entry.value);
      }
    }
    return text;
  }
}

/// 全局取词函数：`t('home.login')`
String t(String key, [Map<String, String>? vars]) => L10n.tr(key, vars);
